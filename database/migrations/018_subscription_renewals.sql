CREATE TABLE IF NOT EXISTS subscription_renewals (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    company_id BIGINT UNSIGNED NOT NULL,
    agreement_id BIGINT UNSIGNED NOT NULL,
    agreement_revision INT UNSIGNED NOT NULL,
    payer_id BIGINT UNSIGNED NOT NULL,
    term_end DATE NOT NULL,
    currency CHAR(3) CHARACTER SET ascii NOT NULL,
    forecast_minor BIGINT UNSIGNED NOT NULL,
    exposure JSON NOT NULL,
    owner_id BIGINT UNSIGNED NOT NULL,
    follow_up DATE,
    retention_action VARCHAR(400),
    state ENUM('open','working','renewed','lost') NOT NULL DEFAULT 'open',
    close_reason VARCHAR(400),
    signed_agreement_id BIGINT UNSIGNED,
    signed_revision INT UNSIGNED,
    signed_minor BIGINT UNSIGNED NOT NULL DEFAULT 0,
    version INT UNSIGNED NOT NULL DEFAULT 1,
    UNIQUE KEY subscription_renewal_cycle (company_id,agreement_id,term_end),
    UNIQUE KEY subscription_renewal_signed (company_id,signed_agreement_id,signed_revision),
    KEY renewal_month (company_id,term_end,state,id),
    FOREIGN KEY (company_id,agreement_id,agreement_revision) REFERENCES agreement_versions(company_id,agreement_id,revision),
    FOREIGN KEY (company_id,signed_agreement_id,signed_revision) REFERENCES agreement_versions(company_id,agreement_id,revision),
    FOREIGN KEY (company_id,payer_id) REFERENCES accounts(company_id,id),
    FOREIGN KEY (owner_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
