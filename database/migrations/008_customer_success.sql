CREATE TABLE IF NOT EXISTS success_assignments (
    company_id BIGINT UNSIGNED NOT NULL,
    agreement_id BIGINT UNSIGNED NOT NULL,
    owner_id BIGINT UNSIGNED NOT NULL,
    changed_by BIGINT UNSIGNED NOT NULL,
    version INT UNSIGNED NOT NULL DEFAULT 1,
    changed_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    PRIMARY KEY (company_id, agreement_id),
    KEY success_assignment_owner (company_id, owner_id, agreement_id),
    FOREIGN KEY (company_id, agreement_id) REFERENCES agreements (company_id, id),
    FOREIGN KEY (owner_id) REFERENCES users (id),
    FOREIGN KEY (changed_by) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS health_snapshots (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    company_id BIGINT UNSIGNED NOT NULL,
    account_id BIGINT UNSIGNED NOT NULL,
    agreement_id BIGINT UNSIGNED NOT NULL,
    agreement_revision INT UNSIGNED NOT NULL,
    score TINYINT UNSIGNED NOT NULL,
    band ENUM('healthy','watch','risk') NOT NULL,
    signals JSON NOT NULL,
    model_version SMALLINT UNSIGNED NOT NULL,
    captured_by BIGINT UNSIGNED NOT NULL,
    captured_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UNIQUE KEY health_company_id (company_id, id),
    KEY health_agreement (company_id, agreement_id, captured_at DESC, id DESC),
    KEY health_account (company_id, account_id, captured_at DESC, id DESC),
    KEY health_worklist (company_id, band, captured_at DESC, id DESC),
    CHECK (score <= 100),
    FOREIGN KEY (company_id, account_id) REFERENCES accounts (company_id, id),
    FOREIGN KEY (company_id, agreement_id, agreement_revision) REFERENCES agreement_versions (company_id, agreement_id, revision),
    FOREIGN KEY (captured_by) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS renewals (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    company_id BIGINT UNSIGNED NOT NULL,
    agreement_id BIGINT UNSIGNED NOT NULL,
    agreement_revision INT UNSIGNED NOT NULL,
    opportunity_id BIGINT UNSIGNED NOT NULL,
    owner_id BIGINT UNSIGNED NOT NULL,
    cycle_ends_on DATE NOT NULL,
    next_follow_up DATE,
    state ENUM('scheduled','working','renewed','lost','superseded') NOT NULL DEFAULT 'scheduled',
    outcome_code VARCHAR(48) CHARACTER SET ascii COLLATE ascii_bin,
    outcome_reason VARCHAR(240),
    evidence_ref VARCHAR(160),
    decided_by BIGINT UNSIGNED,
    decided_at DATETIME(6),
    version INT UNSIGNED NOT NULL DEFAULT 1,
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UNIQUE KEY renewal_company_id (company_id, id),
    UNIQUE KEY renewal_cycle (company_id, agreement_id, cycle_ends_on),
    UNIQUE KEY renewal_opportunity (company_id, opportunity_id),
    KEY renewal_worklist (company_id, state, updated_at DESC, id DESC),
    KEY renewal_followup (company_id, owner_id, state, next_follow_up, id),
    FOREIGN KEY (company_id, agreement_id, agreement_revision) REFERENCES agreement_versions (company_id, agreement_id, revision),
    FOREIGN KEY (company_id, opportunity_id) REFERENCES opportunities (company_id, id),
    FOREIGN KEY (owner_id) REFERENCES users (id),
    FOREIGN KEY (decided_by) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE IF NOT EXISTS outreach_jobs (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    company_id BIGINT UNSIGNED NOT NULL,
    renewal_id BIGINT UNSIGNED NOT NULL,
    contact_id BIGINT UNSIGNED NOT NULL,
    contact_version INT UNSIGNED NOT NULL,
    channel ENUM('email','phone') NOT NULL,
    gateway_mode ENUM('replay','webhook') NOT NULL,
    message VARCHAR(1500) NOT NULL,
    state ENUM('queued','blocked','retryable','delivered','replayed','cancelled') NOT NULL DEFAULT 'queued',
    block_reason ENUM('account_frozen','account_unavailable','consent_missing','contact_changed','renewal_closed'),
    last_error ENUM('gateway_configuration','gateway_unconfirmed'),
    idempotency_key CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    provider_reference VARCHAR(160),
    requested_by BIGINT UNSIGNED NOT NULL,
    processed_by BIGINT UNSIGNED,
    attempts INT UNSIGNED NOT NULL DEFAULT 0,
    retry_after DATETIME(6),
    version INT UNSIGNED NOT NULL DEFAULT 1,
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UNIQUE KEY outreach_company_id (company_id, id),
    UNIQUE KEY outreach_operation (company_id, idempotency_key),
    KEY outreach_renewal (company_id, renewal_id, id),
    KEY outreach_worklist (company_id, state, retry_after, id),
    FOREIGN KEY (company_id, renewal_id) REFERENCES renewals (company_id, id),
    FOREIGN KEY (company_id, contact_id) REFERENCES contacts (company_id, id),
    FOREIGN KEY (requested_by) REFERENCES users (id),
    FOREIGN KEY (processed_by) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
