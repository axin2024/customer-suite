CREATE TABLE IF NOT EXISTS subscriptions (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    company_id BIGINT UNSIGNED NOT NULL,
    agreement_id BIGINT UNSIGNED NOT NULL,
    agreement_revision INT UNSIGNED NOT NULL,
    source_company_id BIGINT UNSIGNED NOT NULL,
    quote_id BIGINT UNSIGNED NOT NULL,
    quote_revision INT UNSIGNED NOT NULL,
    line_no SMALLINT UNSIGNED NOT NULL,
    payer_id BIGINT UNSIGNED NOT NULL,
    service_company_id BIGINT UNSIGNED NOT NULL,
    service_account_id BIGINT UNSIGNED NOT NULL,
    seats INT UNSIGNED NOT NULL,
    plan_id BIGINT UNSIGNED NOT NULL,
    entitlement_rev INT UNSIGNED NOT NULL,
    term_start DATE NOT NULL,
    term_end DATE NOT NULL,
    paid_from DATE,
    billing_timezone VARCHAR(64) CHARACTER SET ascii NOT NULL,
    opening_digest CHAR(64) CHARACTER SET ascii NOT NULL,
    version INT UNSIGNED NOT NULL DEFAULT 1,
    opened_by BIGINT UNSIGNED NOT NULL,
    opened_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    UNIQUE KEY subscription_company_id (company_id,id),
    UNIQUE KEY beneficiary_term (company_id,agreement_id,line_no,service_company_id,service_account_id,term_start),
    KEY subscription_expiry (company_id,term_end,agreement_id),
    FOREIGN KEY (company_id,agreement_id,agreement_revision) REFERENCES agreement_versions(company_id,agreement_id,revision),
    FOREIGN KEY (source_company_id,quote_id,quote_revision,line_no) REFERENCES quote_lines(company_id,quote_id,revision,line_no),
    FOREIGN KEY (company_id,plan_id,entitlement_rev) REFERENCES subscription_rates(company_id,plan_id,revision),
    FOREIGN KEY (company_id,payer_id) REFERENCES accounts(company_id,id),
    FOREIGN KEY (service_company_id,service_account_id) REFERENCES accounts(company_id,id),
    FOREIGN KEY (opened_by) REFERENCES users(id),
    CHECK (term_start < term_end AND seats > 0),
    CHECK (paid_from IS NULL OR (paid_from >= term_start AND paid_from < term_end))
) ENGINE=InnoDB;
